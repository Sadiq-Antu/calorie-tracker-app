export const REFERENCE_FOOD_CATEGORIES = [
  'All',
  'Proteins & Meat',
  'Dairy & Eggs',
  'Grains & Bread',
  'Produce & Fruit',
  'Legumes, Nuts & Seeds',
  'Fats & Oils',
  'Beverages',
  'Prepared & Staples',
] as const;

export function searchReferenceFoods(
  query: string,
  category: string = 'All'
): ReferenceFoodItem[] {
  const normalizedQuery = query.trim().toLowerCase();
  const tokens = normalizedQuery.split(/\s+/).filter(Boolean);

  return VERIFIED_REFERENCE_FOODS.filter((item) => {
    if (category && category !== 'All' && item.category !== category) {
      return false;
    }
    if (tokens.length === 0) {
      return true;
    }
    const searchable = `${item.name} ${item.category} ${item.brand || ''} ${item.usdaFdcId}`.toLowerCase();
    return tokens.every((token) => searchable.includes(token));
  });
}
